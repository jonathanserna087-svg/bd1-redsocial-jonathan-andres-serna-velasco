-- TAREA 6: EXTENSION INCREMENTAL DEL MODELO FISICO DE LAS TAREAS 2-4.
-- REQUISITO: ejecutar primero 01_ddl_base_24_tablas.sql en una base de datos NUEVA.
-- Se conservan las 24 tablas originales y el esquema red_social.
BEGIN;
SET LOCAL search_path TO red_social, public;

-- PUBLICACION ya posee datos_nosql JSONB e indice GIN desde Tarea 4.
-- Se reutilizan ambos elementos, con restriccion de estructura externa.
ALTER TABLE publicacion ALTER COLUMN datos_nosql SET DEFAULT '{}'::jsonb;
ALTER TABLE publicacion
  ADD CONSTRAINT ck_publicacion_nosql_objeto
  CHECK (datos_nosql IS NULL OR jsonb_typeof(datos_nosql)='object');
COMMENT ON COLUMN publicacion.datos_nosql IS
  'JSONB heredado de Tarea 4: iot_telemetria, big_data_metadata y atributos variables del contenido.';

-- Ampliacion nueva en EVENTO para datos semiestructurados de cada encuentro.
ALTER TABLE evento
  ADD COLUMN IF NOT EXISTS detalles_jsonb JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE evento
  ADD CONSTRAINT ck_evento_detalles_objeto
  CHECK (jsonb_typeof(detalles_jsonb) = 'object');
COMMENT ON COLUMN evento.detalles_jsonb IS 'Configuracion variable del evento y recursos requeridos.';

-- La tabla base USUARIO conserva nombre, biografia y relaciones normalizadas.
-- JSONB solo almacena preferencias no normalizadas de interfaz y notificaciones.
CREATE TABLE perfil_configuracion (
  id_usuario INTEGER PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  preferencias JSONB NOT NULL DEFAULT '{}'::jsonb,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_perfil_preferencias_objeto CHECK (jsonb_typeof(preferencias) = 'object')
);
COMMENT ON TABLE perfil_configuracion IS 'Extension 1:1 del usuario para configuracion flexible de interfaz.';

CREATE TABLE espacio_campus (
  id_espacio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  tipo VARCHAR(25) NOT NULL CHECK (tipo IN ('LABORATORIO','BIBLIOTECA','AUDITORIO')),
  capacidad INTEGER NOT NULL CHECK (capacidad > 0),
  ubicacion VARCHAR(150) NOT NULL
);
COMMENT ON TABLE espacio_campus IS 'Espacios fisicos de campus con capacidad para sensores de ocupacion.';

CREATE TABLE dispositivo_iot (
  id_dispositivo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_espacio INTEGER NOT NULL REFERENCES espacio_campus(id_espacio) ON DELETE RESTRICT,
  codigo VARCHAR(40) NOT NULL UNIQUE,
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('OCUPACION','TEMPERATURA')),
  estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
         CHECK (estado IN ('ACTIVO','MANTENIMIENTO','INACTIVO')),
  configuracion JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT ck_dispositivo_config_objeto CHECK (jsonb_typeof(configuracion) = 'object')
);
COMMENT ON TABLE dispositivo_iot IS 'Catalogo normalizado de dispositivos; configuracion tecnica flexible JSONB.';

-- Registro de telemetria de alto volumen. PK incluye fecha de particion (regla PostgreSQL).
CREATE TABLE lectura_iot (
  id_lectura BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_dispositivo INTEGER NOT NULL REFERENCES dispositivo_iot(id_dispositivo) ON DELETE RESTRICT,
  registrado_en TIMESTAMPTZ NOT NULL,
  valor NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
  unidad VARCHAR(15) NOT NULL CHECK (unidad IN ('personas','celsius')),
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT ck_lectura_payload_objeto CHECK (jsonb_typeof(payload) = 'object'),
  PRIMARY KEY (registrado_en,id_lectura)
) PARTITION BY RANGE(registrado_en);
CREATE TABLE lectura_iot_2026_10 PARTITION OF lectura_iot
  FOR VALUES FROM ('2026-10-01 00:00:00-05') TO ('2026-11-01 00:00:00-05');
CREATE TABLE lectura_iot_2026_11 PARTITION OF lectura_iot
  FOR VALUES FROM ('2026-11-01 00:00:00-05') TO ('2026-12-01 00:00:00-05');
CREATE TABLE lectura_iot_2026_12 PARTITION OF lectura_iot
  FOR VALUES FROM ('2026-12-01 00:00:00-05') TO ('2027-01-01 00:00:00-05');
CREATE TABLE lectura_iot_otros PARTITION OF lectura_iot DEFAULT;

-- Eventos digitales de usuario; no registra contrasenas, tokens ni IP completas.
CREATE TABLE registro_actividad (
  id_registro BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_usuario INTEGER REFERENCES usuario(id_usuario) ON DELETE SET NULL,
  registrado_en TIMESTAMPTZ NOT NULL,
  accion VARCHAR(40) NOT NULL,
  metadatos JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT ck_actividad_metadatos_objeto CHECK (jsonb_typeof(metadatos) = 'object'),
  PRIMARY KEY (registrado_en,id_registro)
) PARTITION BY RANGE(registrado_en);
CREATE TABLE registro_actividad_2026_10 PARTITION OF registro_actividad
  FOR VALUES FROM ('2026-10-01 00:00:00-05') TO ('2026-11-01 00:00:00-05');
CREATE TABLE registro_actividad_2026_11 PARTITION OF registro_actividad
  FOR VALUES FROM ('2026-11-01 00:00:00-05') TO ('2026-12-01 00:00:00-05');
CREATE TABLE registro_actividad_2026_12 PARTITION OF registro_actividad
  FOR VALUES FROM ('2026-12-01 00:00:00-05') TO ('2027-01-01 00:00:00-05');
CREATE TABLE registro_actividad_otros PARTITION OF registro_actividad DEFAULT;
COMMIT;
